import XCTest

@testable import MeroKit

/// Account roots, recovery phrases and cloud proofs (port of mero-js
/// `account.test.ts`). Where mero-js compares two deterministic signatures,
/// these verify both: CryptoKit's Ed25519 is randomized.
final class AccountRootTests: XCTestCase {
    /// SHA-256 of the canonical BIP39 English list, newline-joined with a trailing newline.
    private static let wordlistSHA256 = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"

    private static let phrase7F =
        "legal winner thank year wave sausage worth useful legal winner thank year wave sausage worth useful "
        + "legal winner thank year wave sausage worth title"
    private static let phrase80 =
        "letter advice cage absurd amount doctor acoustic avoid letter advice cage absurd amount doctor acoustic "
        + "avoid letter advice cage absurd amount doctor acoustic bless"

    /// The standard 256-bit BIP39 vectors: what makes this a *BIP39* encoder.
    private static let vectors: [(fill: UInt8, phrase: String)] = [
        (0x00, String(repeating: "abandon ", count: 23) + "art"),
        (0x7F, phrase7F),
        (0x80, phrase80),
        (0xFF, String(repeating: "zoo ", count: 23) + "vote"),
    ]

    /// A fixed valid phrase: a random one passes the 8-bit checksum after a
    /// mutation about 1 time in 256.
    private static var knownPhrase: String { phrase7F }

    private static let mdmaRoot = String(repeating: "42", count: 32)
    private static let mdmaRootPublicKey = "2152f8d19b791d24453242e15f2eab6cb7cffa7b6a5ed30097960e069881db12"
    private static let mdmaNonce =
        "eyJleHAiOjE3MDAwMDAzMDAwMDAsImp0aSI6ImFiYyIsInN1YiI6ImRldkBleGFtcGxlLmNvbSJ9.dGFn"
    /// Generated by mdma's own signer and accepted by `verify_account_link_proof`.
    private static let mdmaLinkSignature =
        "DY8dielYG6sNnZOI7zgPy7aO1XFMa5bhOJCJOMOeFHuTtwaC95rG1W0E5U2nyxtQ37CeJdbVPALUf9RgHCwYCw=="

    private func verifies(_ base64: String, publicKey: String, message: Data) -> Bool {
        guard let signature = Data(base64Encoded: base64),
            let key = try? Hex.decode(publicKey, label: "publicKey", bytes: 32)
        else { return false }
        return Ed25519.verify(publicKey: key, signature: signature, message: message)
    }

    private func expectError(_ pattern: String, _ body: () throws -> Void) {
        do {
            try body()
            XCTFail("expected an error matching \(pattern)")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains(pattern), "\(error.localizedDescription)")
        }
    }

    // MARK: - The vendored wordlist

    func testWordlistIsTheCanonicalBip39EnglishList() {
        let joined = bip39EnglishWordlist.joined(separator: "\n") + "\n"
        XCTAssertEqual(Hex.encode(sha256(Data(joined.utf8))), Self.wordlistSHA256)
    }

    func testWordlistHas2048WordsInIndexOrder() {
        XCTAssertEqual(bip39EnglishWordlist.count, 2048)
        XCTAssertEqual(bip39EnglishWordlist.first, "abandon")
        XCTAssertEqual(bip39EnglishWordlist.last, "zoo")
        XCTAssertEqual(bip39EnglishWordlist, bip39EnglishWordlist.sorted())
    }

    // MARK: - Recovery phrases

    func testEncodesTheStandardVectors() throws {
        for vector in Self.vectors {
            let secret = Hex.encode(Data(repeating: vector.fill, count: 32))
            let restored = try accountRootFromPhrase(vector.phrase)
            XCTAssertEqual(restored.secret, secret, vector.phrase)
            XCTAssertEqual(encodePhrase(Data(repeating: vector.fill, count: 32)), vector.phrase)
            XCTAssertEqual(try accountRootFromPhrase(restored.phrase).phrase, vector.phrase)
        }
    }

    func testRoundTripsAFreshlyMintedRoot() throws {
        let minted = try generateAccountRoot()
        XCTAssertEqual(minted.phrase.split(separator: " ").count, 24)
        let restored = try accountRootFromPhrase(minted.phrase)
        XCTAssertEqual(restored, minted)
    }

    func testMintsADifferentRootEveryTime() throws {
        XCTAssertNotEqual(try generateAccountRoot().secret, try generateAccountRoot().secret)
    }

    func testNormalisesCaseAndWhitespace() throws {
        let minted = try generateAccountRoot()
        let mangled = "  " + minted.phrase.uppercased().split(separator: " ").joined(separator: "   ") + "\n"
        XCTAssertEqual(try accountRootFromPhrase(mangled).secret, minted.secret)
    }

    func testRefusesAMistypedWord() {
        var words = Self.knownPhrase.split(separator: " ").map(String.init)
        // A real word in the wrong place: only the checksum catches it.
        words[0] = "abandon"
        expectError("checksum failed") { _ = try accountRootFromPhrase(words.joined(separator: " ")) }
    }

    func testRefusesAWordOutsideTheList() throws {
        var words = try generateAccountRoot().phrase.split(separator: " ").map(String.init)
        words[5] = "calimero"
        expectError("not a word in the recovery phrase list") {
            _ = try accountRootFromPhrase(words.joined(separator: " "))
        }
    }

    func testRefusesAWrongWordCount() {
        expectError("recovery phrase must be 24 words, got 0") { _ = try accountRootFromPhrase("") }
        expectError("recovery phrase must be 24 words, got 3") {
            _ = try accountRootFromPhrase("abandon abandon abandon")
        }
    }

    // MARK: - Account derivation

    func testNamesTheAccountMdmaDerives() throws {
        let root = try accountRootFromSecret(Self.mdmaRoot)
        XCTAssertEqual(root.publicKey, Self.mdmaRootPublicKey)
        XCTAssertEqual(root.accountId, "a71c3dd073939d81f972525e9788c6b958818e33f30674ef43b4184eef40aa50")
    }

    func testRejectsASecretThatIsNot32Bytes() {
        expectError("must be 64 hex characters") { _ = try accountRootFromSecret("4242") }
    }

    // MARK: - signAccountLink / signAccountLogin

    func testMdmasPinnedSignatureIsOverTheDomainPrefixedNonce() {
        // Pins the domain separator, NUL included: mdma's own signature verifies
        // over exactly the bytes signed here, and not over the bare nonce.
        let prefixed = accountLinkDomain + Data(Self.mdmaNonce.utf8)
        XCTAssertTrue(verifies(Self.mdmaLinkSignature, publicKey: Self.mdmaRootPublicKey, message: prefixed))
        XCTAssertFalse(
            verifies(Self.mdmaLinkSignature, publicKey: Self.mdmaRootPublicKey, message: Data(Self.mdmaNonce.utf8)))
    }

    func testSignsTheLinkMdmaVerifies() async throws {
        let signature = try await signAccountLink(AccountLinkInput(rootSecret: Self.mdmaRoot, nonce: Self.mdmaNonce))
        let prefixed = accountLinkDomain + Data(Self.mdmaNonce.utf8)
        XCTAssertTrue(verifies(signature, publicKey: Self.mdmaRootPublicKey, message: prefixed))
        XCTAssertFalse(verifies(signature, publicKey: Self.mdmaRootPublicKey, message: Data(Self.mdmaNonce.utf8)))
    }

    func testEmitsStandardBase64() async throws {
        let signature = try await signAccountLink(AccountLinkInput(rootSecret: Self.mdmaRoot, nonce: Self.mdmaNonce))
        XCTAssertNotNil(signature.range(of: "^[A-Za-z0-9+/]+={0,2}$", options: .regularExpression))
        XCTAssertEqual(Data(base64Encoded: signature)?.count, 64)
    }

    func testRefusesAnEmptyNonce() async {
        do {
            _ = try await signAccountLink(AccountLinkInput(rootSecret: Self.mdmaRoot, nonce: ""))
            XCTFail("expected a refusal")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains("nonce is required"))
        }
    }

    func testLoginSignsUnderItsOwnDomain() async throws {
        let signature = try await signAccountLogin(AccountLoginInput(rootSecret: Self.mdmaRoot, nonce: "challenge"))
        let login = accountLoginDomain + Data("challenge".utf8)
        let link = accountLinkDomain + Data("challenge".utf8)
        XCTAssertTrue(verifies(signature, publicKey: Self.mdmaRootPublicKey, message: login))
        // A link signature must not be replayable as a login, and vice versa.
        XCTAssertFalse(verifies(signature, publicKey: Self.mdmaRootPublicKey, message: link))
    }

    func testRefusesASecretAndASignerAtOnce() async throws {
        let signer = try accountRootSignerFromPhrase(try generateAccountRoot().phrase).signer
        do {
            _ = try await signAccountLink(
                AccountLinkInput(rootSecret: String(repeating: "07", count: 32), signer: signer, nonce: "n"))
            XCTFail("expected a refusal")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains("either rootSecret or signer, not both"))
        }
    }

    func testRefusesNeither() async {
        do {
            _ = try await signAccountLink(AccountLinkInput(nonce: "n"))
            XCTFail("expected a refusal")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains("rootSecret or signer is required"))
        }
    }

    // MARK: - A root that stays in its signer

    func testRestoresTheSameAccountFromThePhraseItHandsBack() throws {
        let created = try createAccountRootSigner()
        let restored = try accountRootSignerFromPhrase(created.phrase)
        XCTAssertEqual(restored.accountId, created.accountId)
        XCTAssertEqual(restored.publicKey, created.publicKey)
        XCTAssertEqual(created.phrase.split(separator: " ").count, 24)
    }

    func testAgreesWithTheSecretBearingDerivation() throws {
        let phrase = try generateAccountRoot().phrase
        let withSecret = try accountRootFromPhrase(phrase)
        let withSigner = try accountRootSignerFromPhrase(phrase)
        XCTAssertEqual(withSigner.accountId, withSecret.accountId)
        XCTAssertEqual(withSigner.publicKey, withSecret.publicKey)
        let resolved = try resolveRoot(.signer(withSigner.signer))
        XCTAssertEqual(resolved.accountId, withSecret.accountId)
        XCTAssertEqual(try resolveRoot(.secret(withSecret.secret)).accountId, withSecret.accountId)
    }

    func testSignsThroughTheSignerWhatTheSecretSigns() async throws {
        let phrase = try generateAccountRoot().phrase
        let root = try accountRootFromPhrase(phrase)
        let signer = try accountRootSignerFromPhrase(phrase).signer
        let fromSigner = try await signAccountLink(AccountLinkInput(signer: signer, nonce: "challenge"))
        let fromSecret = try await signAccountLink(AccountLinkInput(rootSecret: root.secret, nonce: "challenge"))
        let message = accountLinkDomain + Data("challenge".utf8)
        XCTAssertTrue(verifies(fromSigner, publicKey: root.publicKey, message: message))
        XCTAssertTrue(verifies(fromSecret, publicKey: root.publicKey, message: message))
    }

    func testRefusesATransposedPhrase() {
        var words = Self.knownPhrase.split(separator: " ").map(String.init)
        words.swapAt(0, 1)
        expectError("checksum failed") { _ = try accountRootSignerFromPhrase(words.joined(separator: " ")) }
    }

    func testAVaultKeepsTheRootAcrossALoad() async throws {
        let vault = MemoryRootSeedVault()
        let created = try createAccountRootSigner(vault: vault)
        XCTAssertNotNil(try vault.load())
        let reopened = try XCTUnwrap(try loadAccountRootSigner(from: vault))
        XCTAssertEqual(reopened.accountId, created.accountId)
        let signature = try await reopened.signer.sign(Data("payload".utf8))
        let key = try Hex.decode(created.publicKey, label: "publicKey", bytes: 32)
        XCTAssertTrue(Ed25519.verify(publicKey: key, signature: signature, message: Data("payload".utf8)))

        try vault.delete()
        XCTAssertNil(try loadAccountRootSigner(from: vault))
        do {
            _ = try await created.signer.sign(Data())
            XCTFail("a deleted root still signed")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains("holds no account root"))
        }
    }

    func testAVaultSignerRefusesARootSwappedUnderIt() async throws {
        let vault = MemoryRootSeedVault()
        let created = try createAccountRootSigner(vault: vault)
        _ = try accountRootSignerFromPhrase(try generateAccountRoot().phrase, vault: vault)
        do {
            _ = try await created.signer.sign(Data())
            XCTFail("signed with another account's root")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains("different account root"))
        }
    }

    func testResolveRootPairTakesExactlyOne() throws {
        let signer = try signerFromSecret(Self.mdmaRoot)
        XCTAssertEqual(try resolveRootPair(rootSecret: nil, signer: signer).publicKey, Self.mdmaRootPublicKey)
        XCTAssertEqual(try resolveRootPair(rootSecret: Self.mdmaRoot, signer: nil).publicKey, Self.mdmaRootPublicKey)
        XCTAssertThrowsError(try resolveRootPair(rootSecret: nil, signer: nil))
        XCTAssertThrowsError(try resolveRootPair(rootSecret: Self.mdmaRoot, signer: signer))
    }
}
