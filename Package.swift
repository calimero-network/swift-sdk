// swift-tools-version: 5.9
import PackageDescription

let package = Package(
    name: "MeroKit",
    platforms: [
        .iOS(.v15),
        .macOS(.v12),
    ],
    products: [
        .library(name: "MeroKit", targets: ["MeroKit"]),
        // The client swift-openapi-generator generated from core's OpenAPI
        // document (openapi/openapi.json): its `Client`, `Operations` and
        // `Components`. `import MeroAPI` to name the types the facade
        // (`client.orgs.get(org:)`, ...) answers.
        .library(name: "MeroAPI", targets: ["MeroAPI"]),
        .library(name: "MeroKitUI", targets: ["MeroKitUI"]),
        // Test doubles for apps' own tests: `FakeNode` (a stateful fake node) and
        // `MockURLProtocol`. Depend on it from a test target only — it is not part
        // of `MeroKit`. (== the Kotlin SDK's `mero-testkit`.)
        .library(name: "MeroKitTestSupport", targets: ["MeroKitTestSupport"]),
        .executable(name: "MeroExample", targets: ["MeroExample"]),
    ],
    // Exact: the generated sources are written for these releases
    // (scripts/generate-openapi.sh, generator 1.10.3), and both still build
    // with Swift 5.9.
    dependencies: [
        .package(url: "https://github.com/apple/swift-openapi-runtime", exact: "1.9.0"),
        .package(url: "https://github.com/apple/swift-http-types", exact: "1.5.1"),
    ],
    targets: [
        // Generated by scripts/generate-openapi.sh from openapi/openapi.json
        // and checked in; never edited by hand (CI checks it is current).
        .target(
            name: "MeroAPI",
            dependencies: [
                .product(name: "OpenAPIRuntime", package: "swift-openapi-runtime"),
                .product(name: "HTTPTypes", package: "swift-http-types"),
            ]
        ),
        .target(
            name: "MeroKit",
            dependencies: [
                "MeroAPI",
                .product(name: "OpenAPIRuntime", package: "swift-openapi-runtime"),
                .product(name: "HTTPTypes", package: "swift-http-types"),
            ],
            swiftSettings: [
                .enableExperimentalFeature("StrictConcurrency"),
            ]
        ),
        // SwiftUI "frontend" layer: an observable MeroClient + Login/Home views.
        // The native analog of mero-react's MeroProvider/useMero + LoginModal.
        .target(
            name: "MeroKitUI",
            dependencies: ["MeroKit", "MeroAPI", .product(name: "OpenAPIRuntime", package: "swift-openapi-runtime")],
            swiftSettings: [
                .enableExperimentalFeature("StrictConcurrency"),
            ]
        ),
        // A runnable end-to-end example that exercises the whole SDK.
        .executableTarget(
            name: "MeroExample",
            dependencies: ["MeroKit", "MeroAPI"],
            swiftSettings: [
                .enableExperimentalFeature("StrictConcurrency"),
            ]
        ),
        // Reusable test doubles: a URLProtocol stub + a stateful fake node
        // (nock/msw analog). Shared by every test target below, and shipped as
        // the `MeroKitTestSupport` product for apps' own tests.
        .target(
            name: "MeroKitTestSupport",
            dependencies: ["MeroKit"]
        ),
        // Unit tests + fully-mocked end-to-end journeys (no node required).
        .testTarget(
            name: "MeroKitTests",
            dependencies: ["MeroKit", "MeroAPI", "MeroKitTestSupport"],
            // Response bodies captured verbatim from a live node at the pinned
            // core release. Kept as files rather than string literals so they
            // stay diffable against a re-capture after a core bump — see
            // Tests/MeroKitTests/Fixtures/README.md.
            resources: [.copy("Fixtures")],
            swiftSettings: [
                .enableExperimentalFeature("StrictConcurrency"),
            ]
        ),
        // View-model tests for the SwiftUI frontend (fast; no simulator needed).
        .testTarget(
            name: "MeroKitUITests",
            dependencies: ["MeroKit", "MeroKitUI", "MeroKitTestSupport"],
            swiftSettings: [
                .enableExperimentalFeature("StrictConcurrency"),
            ]
        ),
        // Real end-to-end tests against a live node. Skipped automatically unless
        // MERO_E2E_NODE_URL is set (see .github/workflows/e2e.yml).
        .testTarget(
            name: "MeroKitE2ETests",
            dependencies: ["MeroKit", "MeroAPI"],
            swiftSettings: [
                .enableExperimentalFeature("StrictConcurrency"),
            ]
        ),
    ]
)
