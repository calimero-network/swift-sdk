#!/usr/bin/env bash
# MeroAPI: the Swift client generated from core's OpenAPI document.
#
#   scripts/generate-openapi.sh                 regenerate Sources/MeroAPI/Generated from openapi/openapi.json
#   scripts/generate-openapi.sh refresh [REF]   vendor the document from core at REF (default: openapi/source's
#                                               CORE_REF), record its commit, then regenerate
#   scripts/generate-openapi.sh check           exit 1 if the checked-in sources differ from a fresh generation
#
# openapi/openapi.json is core's document byte for byte (core generates it
# from `crates/node/src/api/openapi.rs`); openapi/source records the commit.
# scripts/openapi-normalize.py rewrites a copy into the dialect the generator
# reads, swift-openapi-generator (GENERATOR_VERSION, built once into
# $MERO_OPENAPI_CACHE) writes Types.swift and Client.swift, and this script
# stamps them; scripts/generate-facade.py then writes MeroKit's facade over
# them (Sources/MeroKit/Api/Generated/Facade.swift: `client.orgs.get(org:)`,
# ...). The output is checked in so that building MeroKit never runs
# the generator or needs its plugin; CI's `generated` job runs `check`.
#
# GENERATOR=/path/to/swift-openapi-generator skips building it (it must be
# GENERATOR_VERSION). Needs git, python3 and a Swift toolchain (macOS or Linux).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SOURCE="$ROOT/openapi/source"
SPEC="$ROOT/openapi/openapi.json"
CONFIG="$ROOT/openapi/openapi-generator-config.yaml"
OUT="$ROOT/Sources/MeroAPI/Generated"
FACADE="$ROOT/Sources/MeroKit/Api/Generated/Facade.swift"
# shellcheck source=/dev/null
. "$SOURCE"
CACHE="${MERO_OPENAPI_CACHE:-$ROOT/.build/openapi-generator}"

die() { echo "generate-openapi: $*" >&2; exit 1; }

# The generator at GENERATOR_VERSION, built from source on first use.
generator() {
  if [ -n "${GENERATOR:-}" ]; then echo "$GENERATOR"; return; fi
  local src="$CACHE/swift-openapi-generator-$GENERATOR_VERSION"
  local bin="$src/.build/release/swift-openapi-generator"
  if [ ! -x "$bin" ]; then
    rm -rf "$src"
    mkdir -p "$CACHE"
    git clone --quiet --depth 1 --branch "$GENERATOR_VERSION" \
      https://github.com/apple/swift-openapi-generator "$src" >&2
    (cd "$src" && swift build -c release --product swift-openapi-generator >&2)
  fi
  echo "$bin"
}

# Generate into directory $1 (Types.swift, Client.swift) and file $2 (the facade).
generate_into() {
  local dest="$1" facade="$2" work
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' RETURN
  python3 "$ROOT/scripts/openapi-normalize.py" "$SPEC" "$work/openapi.json"
  "$(generator)" generate "$work/openapi.json" --config "$CONFIG" --output-directory "$work/out" >"$work/log" 2>&1 \
    || { cat "$work/log" >&2; die "the generator failed"; }
  # A warning means a schema was skipped, and with it a property: fail rather than ship the gap.
  if grep -iE '(warning|error):' "$work/log" >&2; then die "the generator warned (above); fix the normalization"; fi
  mkdir -p "$dest"
  for file in Types.swift Client.swift; do
    {
      echo "// swift-format-ignore-file"
      echo "// swiftlint:disable all"
      echo "// Generated by scripts/generate-openapi.sh (swift-openapi-generator $GENERATOR_VERSION) from"
      echo "// openapi/openapi.json, $CORE_REPO@$CORE_COMMIT. Do not edit."
      cat "$work/out/$file"
    } >"$dest/$file"
  done
  mkdir -p "$(dirname "$facade")"
  python3 "$ROOT/scripts/generate-facade.py" "$SPEC" "$dest/Types.swift" "$facade"
}

refresh() {
  local ref="${1:-$CORE_REF}" commit
  commit="$(git ls-remote "https://github.com/$CORE_REPO" "$ref" | awk 'NR==1 {print $1}')"
  if [ -z "$commit" ]; then
    # A commit id rather than a branch or tag.
    [[ "$ref" =~ ^[0-9a-f]{40}$ ]] || die "no ref $ref in $CORE_REPO"
    commit="$ref"
  fi
  curl -fsSL "https://raw.githubusercontent.com/$CORE_REPO/$commit/$CORE_PATH" -o "$SPEC.new"
  python3 -c 'import json, sys; json.load(open(sys.argv[1]))' "$SPEC.new" || die "$CORE_PATH at $commit is not JSON"
  mv "$SPEC.new" "$SPEC"
  sed -i.bak -e "s|^CORE_REF=.*|CORE_REF=$ref|" -e "s|^CORE_COMMIT=.*|CORE_COMMIT=$commit|" "$SOURCE"
  rm -f "$SOURCE.bak"
  CORE_REF="$ref"
  CORE_COMMIT="$commit"
  echo "openapi/openapi.json <- $CORE_REPO@$commit ($ref)"
}

case "${1:-generate}" in
  generate)
    generate_into "$OUT" "$FACADE"
    echo "wrote ${OUT#"$ROOT"/} and ${FACADE#"$ROOT"/}"
    ;;
  refresh)
    refresh "${2:-}"
    generate_into "$OUT" "$FACADE"
    echo "wrote ${OUT#"$ROOT"/} and ${FACADE#"$ROOT"/}"
    ;;
  check)
    fresh="$(mktemp -d)"
    changes="$(mktemp)"
    trap 'rm -rf "$fresh" "$changes"' EXIT
    generate_into "$fresh/MeroAPI" "$fresh/Facade.swift"
    stale=0
    diff -ru "$OUT" "$fresh/MeroAPI" >"$changes" || stale=1
    diff -u "$FACADE" "$fresh/Facade.swift" >>"$changes" || stale=1
    if [ "$stale" = 1 ]; then
      head -100 "$changes" >&2
      die "the generated sources are stale: run scripts/generate-openapi.sh and commit the result"
    fi
    echo "Sources/MeroAPI/Generated and the facade match openapi/openapi.json"
    ;;
  *)
    sed -n '2,21p' "$0" >&2
    exit 2
    ;;
esac
